#!/usr/bin/env python3
"""Generate core/src/region_tables.inc from the band dump (ADR-0023).

  cd tools/regions/banddump && go run . > /tmp/dump.json
  tools/regions/gen_tables.py /tmp/dump.json > core/src/region_tables.inc

The dump comes from github.com/brocaar/lorawan/band (MIT, pinned in go.mod),
RP002-1.0.3 values for LoRaWAN 1.0.4, repeater-compatible sizes. The fixed
channel plans (US915, AU915) are checked against their rule here, so the C
code can compute channels instead of listing 72.
"""
import json
import sys

REGIONS = [  # C id, dump name
    ("LWC_REGION_EU868", "EU868"),
    ("LWC_REGION_US915", "US915"),
    ("LWC_REGION_AU915", "AU915"),
    ("LWC_REGION_AS923_1", "AS923"),
    ("LWC_REGION_AS923_2", "AS923-2"),
    ("LWC_REGION_AS923_3", "AS923-3"),
    ("LWC_REGION_AS923_4", "AS923-4"),
    ("LWC_REGION_IN865", "IN865"),
    ("LWC_REGION_KR920", "KR920"),
    ("LWC_REGION_RU864", "RU864"),
]
KIND = {"LORA": "LWC_DR_LORA", "FSK": "LWC_DR_FSK", "LR_FHSS": "LWC_DR_LRFHSS"}


def get(d, name, dwell):
    m = [x for x in d if x["name"] == name and x["proto"] == "1.0.4" and x["dwell"] == dwell and x["repeater"]]
    if len(m) != 1:
        sys.exit("no single entry for %s dwell=%s" % (name, dwell))
    return m[0]


def dwell_floor(e, ed, drs):
    """The RX1 DR table with the downlink dwell limit is the plain one raised
    to a floor (AS923: DR2). Find the floor, and check that it is only that."""
    for fl in range(8):
        if all((max(v, fl) if v >= 0 else v) == w
               for i, (r, q) in enumerate(zip(e["rx1_dr"], ed["rx1_dr"])) if i in drs
               for v, w in zip(r, q)):
            return fl
    sys.exit("%s: the dwell RX1 DR table is not a floor" % e["name"])


def fixed_rule(e):
    """Uplink 0-63 at 125 kHz and 64-71 at 500 kHz, downlink 0-7: base and step, checked."""
    up, down = e["uplink"], e["downlink"]
    if len(up) != 72 or len(down) != 8:
        sys.exit("%s: not a 64+8 plan" % e["name"])
    b125, s125 = up[0]["freq"], up[1]["freq"] - up[0]["freq"]
    b500, s500 = up[64]["freq"], up[65]["freq"] - up[64]["freq"]
    bd, sd = down[0]["freq"], down[1]["freq"] - down[0]["freq"]
    for i in range(64):
        assert up[i]["freq"] == b125 + i * s125, (e["name"], i)
    for i in range(8):
        assert up[64 + i]["freq"] == b500 + i * s500, (e["name"], 64 + i)
        assert down[i]["freq"] == bd + i * sd, (e["name"], "down", i)
    for i in range(72):
        assert e["rx1_channel_for_uplink"][i] == i % 8, (e["name"], "rx1", i)
    dr125 = (up[0]["min_dr"], up[0]["max_dr"])
    dr500 = (up[64]["min_dr"], up[64]["max_dr"])
    drd = (down[0]["min_dr"], down[0]["max_dr"])
    return b125, s125, dr125, b500, s500, dr500, bd, sd, drd


def main():
    d = json.load(open(sys.argv[1]))
    out = []
    w = out.append
    w("/* Generated by tools/regions/gen_tables.py from github.com/brocaar/lorawan/band")
    w(" * (MIT; version in tools/regions/banddump/go.mod): RP002-1.0.3, LoRaWAN 1.0.4,")
    w(" * repeater-compatible sizes. Do not edit by hand. */")
    for cid, name in REGIONS:
        e, ed = get(d, name, False), get(d, name, True)
        drs = {x["dr"]: x for x in e["drs"]}
        drd = {x["dr"]: x for x in ed["drs"]}
        w("")
        w("static const lwc_region_t R_%s = {" % name.replace("-", "_"))
        w("    .id = %s," % cid)
        w('    .name = "%s",' % ("AS923-1" if name == "AS923" else name))
        w("    .max_eirp_dbm = %d," % int(e["max_uplink_eirp"]))
        w("    .tx_powers = %d," % len(e["tx_power_offset"]))
        assert all(v == -2 * i for i, v in enumerate(e["tx_power_offset"])), name
        w("    .rx2_hz = %dU," % e["rx2_freq"])
        w("    .rx2_dr = %d," % e["rx2_dr"])
        w("    .tx_param_setup = %s," % ("true" if e["tx_param_setup"] else "false"))
        w("    .dr = {")
        for i in range(16):
            if i not in drs:
                continue
            x = drs[i]
            nd = drd[i]["n"] if i in drd else 0
            w("        [%d] = {%s, %d, %d, %d, %d}," % (i, KIND[x["mod"]], x["sf"], x["bw"], x["n"], nd))
        w("    },")
        w("    .rx1_dr = {")
        for i, row in enumerate(e["rx1_dr"]):  # every row: a missing one would read as DR0
            # The reference fills rows for RFU uplink DRs and some targets that are
            # RFU in the region (KR920 DR7, IN865 DR6): those are -1 (not defined).
            row = [v if i in drs and v in drs else -1 for v in row]
            w("        [%d] = {%s}," % (i, ", ".join(str(v) for v in row)))
        w("    },")
        w("    .rx1_dwell_min_dr = %d," % dwell_floor(e, ed, drs))
        if len(e["uplink"]) == 72:
            b125, s125, dr125, b500, s500, dr500, bd, sd, drd2 = fixed_rule(e)
            w("    .fixed = true,")
            w("    .up125 = {%dU, %dU, %d, %d}," % (b125, s125, dr125[0], dr125[1]))
            w("    .up500 = {%dU, %dU, %d, %d}," % (b500, s500, dr500[0], dr500[1]))
            w("    .down = {%dU, %dU, %d, %d}," % (bd, sd, drd2[0], drd2[1]))
        else:
            w("    .fixed = false,")
            w("    .n_default = %d," % len(e["uplink"]))
            w("    .default_ch = {")
            for c in e["uplink"]:
                w("        {%dU, %d, %d}," % (c["freq"], c["min_dr"], c["max_dr"]))
            w("    },")
            assert [c["freq"] for c in e["downlink"]] == [c["freq"] for c in e["uplink"]], name
        w("};")
    w("")
    w("static const lwc_region_t *const REGIONS[LWC_REGIONS] = {")
    for cid, name in REGIONS:
        w("    [%s] = &R_%s," % (cid, name.replace("-", "_")))
    w("};")
    print("\n".join(out))


def test_ref():
    """core/test/region_ref.inc: the sub-band CFLists and LinkADRReq sets of the
    fixed plans, and per-region RX1 channel mapping samples, for test_region."""
    d = json.load(open(sys.argv[2]))
    out = []
    w = out.append
    w("/* Generated by tools/regions/gen_tables.py --test (reference: brocaar/lorawan/band). */")
    for name in ("US915", "AU915"):
        for proto in ("1.0.2", "1.0.4"):
            e = [x for x in d if x["name"] == name and x["proto"] == proto and not x["dwell"] and x["repeater"]][0]
            for sb in e["sub_bands"]:
                cf = sb["cflist"]
                masks = cf["payload"]["ChannelMasks"] if cf else []
                bits = []
                for m in masks:
                    v = 0
                    for i, on in enumerate(m):
                        v |= (1 << i) if on else 0
                    bits.append(v)
                cmds = [(p["chMask"], p["redundancy"]["chMaskCntl"]) for p in sb["link_adr"]]
                cm = []
                for mask, cntl in cmds:
                    v = 0
                    for i, on in enumerate(mask):
                        v |= (1 << i) if on else 0
                    cm.append("{0x%04X, %d}" % (v, cntl))
                w("{\"%s\", \"%s\", %d, %d, {%s}, %d, {%s}}," % (name, proto, sb["sub_band"], len(bits),
                  ", ".join("0x%04X" % b for b in bits) or "0", len(cm), ", ".join(cm)))
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--test":
        test_ref()
    else:
        main()
